export const THEME_LIST = Object.values(THEMES);

export function applyTheme(themeId) {
  const theme = THEMES[themeId];
  if (!theme) return;
  const root = document.documentElement;
  Object.entries(theme.vars).forEach(([key, value]) => {
    root.style.setProperty(key, value);
  });
  // Set data-theme attribute for group-based styling
  root.setAttribute("data-theme", themeId);
  root.classList.toggle("dark", theme.group === "dark");
  root.classList.toggle("light", theme.group === "light");
  // Update body colors
  document.body.style.backgroundColor = theme.bg;
  document.body.style.color = theme.text;
  // Save to localStorage
  localStorage.setItem("grizon-theme", themeId);
}

export function getSavedTheme() {
  return localStorage.getItem("grizon-theme") || "parchment";
}
